    val VILLAGES: List<Village> by lazy { loadVillages() }

    private fun loadVillages(): List<Village> {
        val stream = APAdministrativeData::class.java.getResourceAsStream("/ap_villages.tsv.gz")
            ?: APAdministrativeData::class.java.classLoader?.getResourceAsStream("ap_villages.tsv.gz")
            ?: APAdministrativeData::class.java.getResourceAsStream("/ap_villages.tsv")
            ?: APAdministrativeData::class.java.classLoader?.getResourceAsStream("ap_villages.tsv")
            ?: return emptyList()

        val list = ArrayList<Village>(18000)
        try {
            val bis = java.io.BufferedInputStream(stream)
            bis.mark(2)
            val header = ByteArray(2)
            val readCount = bis.read(header)
            bis.reset()
            val isGzip = (readCount == 2 && (header[0].toInt() and 0xff) == 0x1f && (header[1].toInt() and 0xff) == 0x8b)
            val effectiveStream = if (isGzip) java.util.zip.GZIPInputStream(bis) else bis

            effectiveStream.bufferedReader(Charsets.UTF_8).useLines { lines ->
                for (line in lines) {
                    if (line.isEmpty()) continue
                    val parts = line.split('	')
                    if (parts.size >= 6) {
                        list.add(
                            Village(
                                id = parts[0],
                                districtId = parts[1],
                                mandalId = parts[2],
                                name = parts[3],
                                code = parts[4],
                                censusCode = parts[5]
                            )
                        )
                    }
                }
            }
        } catch (e: Exception) {
            e.printStackTrace()
        }
        return list
    }

